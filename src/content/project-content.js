const normalize = (value) => String(value ?? "").replace(/\s+/g, " ").trim();

function findScene(root, title, project) {
  const titles = new Set([title, ...(project.aliases ?? [])].map(normalize));
  return [...root.querySelectorAll(".cv-item")].find((scene) =>
    [scene.querySelector(".cv-item__project"), scene.querySelector(".cv-item__title")]
      .map((node) => normalize(node?.textContent))
      .some((value) => titles.has(value)),
  );
}

function firstStoryParagraph(scene) {
  const content = scene.querySelector(".cv-item__content");
  if (!content) return null;
  return [...content.children]
    .find((child) => child.matches(".cv-story") && child.querySelector(".cv-story__copy p"))
    ?.querySelector(".cv-story__copy p");
}

function applyBriefs(scene, briefs = []) {
  const cards = [...scene.querySelectorAll(".brief__card")];
  briefs.slice(0, cards.length).forEach(([title, ...items], index) => {
    const card = cards[index];
    const heading = card.querySelector("h3, h4");
    const list = card.querySelector("ul, ol");
    if (heading) heading.textContent = title;
    if (list) {
      list.replaceChildren(...items.map((text) => {
        const item = document.createElement("li");
        item.textContent = text;
        return item;
      }));
    }
  });
}

export function applyProjectContent(root = document) {
  Object.entries(PROJECTS).forEach(([title, project]) => {
    const scene = findScene(root, title, project);
    if (!scene) return;

    if (project.title) {
      const projectName = scene.querySelector(".cv-item__project");
      const sceneTitle = scene.querySelector(".cv-item__title");
      if (projectName) projectName.textContent = project.title;
      if (sceneTitle) sceneTitle.textContent = project.title;
    }

    const description = scene.querySelector(".cv-item__copy");
    if (description && project.description) description.textContent = project.description;

    const intro = firstStoryParagraph(scene);
    if (intro && project.intro) intro.textContent = project.intro;

    applyBriefs(scene, project.briefs);
  });
}
