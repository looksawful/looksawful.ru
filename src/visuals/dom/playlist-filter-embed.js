  function enhanceScrollable() {
    embedRoot.querySelectorAll('[data-scrollable="x"]').forEach(function (el) {
      el.addEventListener(
        "wheel",
        function (event) {
          if (Math.abs(event.deltaY) > Math.abs(event.deltaX)) {
            event.preventDefault();
            el.scrollLeft += event.deltaY;
          }
        },
        { passive: false },
      );

      let pointerId = null;
      let startX = 0;
      let startScroll = 0;
      let dragged = false;
      let suppressClick = false;

      function resetDrag() {
        pointerId = null;
        dragged = false;
        el.classList.remove("is-dragging");
      }

      el.addEventListener("pointerdown", function (event) {
        const stage = embedRoot.querySelector("[data-animation-stage]");
        if (event.button !== 0 || !stage || !stage.classList.contains("is-interactive")) return;
        if (el.scrollWidth <= el.clientWidth) return;

        pointerId = event.pointerId;
        startX = event.clientX;
        startScroll = el.scrollLeft;
        dragged = false;
        suppressClick = false;
      });

      el.addEventListener("pointermove", function (event) {
        if (pointerId !== event.pointerId) return;
        const distance = event.clientX - startX;

        if (!dragged && Math.abs(distance) >= 6) {
          dragged = true;
          el.classList.add("is-dragging");
        }
        if (!dragged) return;

        event.preventDefault();
        el.scrollLeft = startScroll - distance;
      });

      function finishDrag(event) {
        if (pointerId !== event.pointerId) return;
        suppressClick = dragged;
        resetDrag();
        window.setTimeout(function () {
          suppressClick = false;
        }, 0);
      }

      el.addEventListener("pointerup", finishDrag);
      el.addEventListener("pointercancel", finishDrag);
      el.addEventListener("lostpointercapture", resetDrag);
      el.addEventListener(
        "click",
        function (event) {
          if (!suppressClick) return;
          event.preventDefault();
          event.stopImmediatePropagation();
          suppressClick = false;
        },
        true,
      );
    });
  }

