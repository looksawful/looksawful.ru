    const SHOW_DELAY = 460;
    const HIDE_DELAY = 55;
    let showTimer = 0;
    let hideTimer = 0;
    let activeTarget = null;

    function clearTimers() {
      window.clearTimeout(showTimer);
      window.clearTimeout(hideTimer);
      showTimer = 0;
      hideTimer = 0;
    }

    function hideTooltip(immediate) {
      clearTimers();
      activeTarget = null;

      const hide = function () {
        layer.classList.remove("is-visible");
        layer.setAttribute("aria-hidden", "true");
      };

      if (immediate) hide();
      else hideTimer = window.setTimeout(hide, HIDE_DELAY);
    }

    function placeTooltip(target) {
      const targetRect = target.getBoundingClientRect();
      const rootRect = embedRoot.getBoundingClientRect();
      const tooltipRect = layer.getBoundingClientRect();
      const gap = 8;
      const edge = 10;
      const rootWidth = embedRoot.clientWidth || rootRect.width;
      const rootHeight = embedRoot.clientHeight || rootRect.height;

      let left = targetRect.left - rootRect.left + targetRect.width / 2 - tooltipRect.width / 2;
      let top = targetRect.top - rootRect.top - tooltipRect.height - gap;

      if (top < edge) {
        top = targetRect.bottom - rootRect.top + gap;
      }

      left = Math.max(edge, Math.min(left, rootWidth - tooltipRect.width - edge));
      top = Math.max(edge, Math.min(top, rootHeight - tooltipRect.height - edge));

      layer.style.left = Math.round(left) + "px";
      layer.style.top = Math.round(top) + "px";
    }

    function scheduleTooltip(target) {
      clearTimers();
      activeTarget = target;
      layer.classList.remove("is-visible");
      layer.setAttribute("aria-hidden", "true");

      showTimer = window.setTimeout(function () {
        if (!desktopHover.matches || !stage.classList.contains("is-interactive")) return;
        if (activeTarget !== target || !target.isConnected || !target.matches(":hover")) return;

        layer.textContent = target.dataset.hoverTooltip;
        placeTooltip(target);
        layer.classList.add("is-visible");
        layer.setAttribute("aria-hidden", "false");
      }, SHOW_DELAY);
    }

    document.addEventListener("pointerover", function (event) {
      if (!desktopHover.matches || !stage.classList.contains("is-interactive")) return;
      const target = event.target.closest("[data-hover-tooltip]");
      if (!target || !stage.contains(target)) return;
      if (event.relatedTarget && target.contains(event.relatedTarget)) return;
      scheduleTooltip(target);
    });

    document.addEventListener("pointerout", function (event) {
      const target = event.target.closest("[data-hover-tooltip]");
      if (!target || target !== activeTarget) return;
      if (event.relatedTarget && target.contains(event.relatedTarget)) return;
      hideTooltip(false);
    });

    document.addEventListener(
      "pointerdown",
      function () {
        hideTooltip(true);
      },
      true,
    );
    window.addEventListener("blur", function () {
      hideTooltip(true);
    });
    window.addEventListener("resize", function () {
      hideTooltip(true);
    });
    window.addEventListener(
      "scroll",
      function () {
        hideTooltip(true);
      },
      true,
    );
